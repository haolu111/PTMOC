/**
 * 获取所有可选起点
 */
export function getStartPoints() {
  return [...new Set(ROUTE_COMBOS.map(r => r.start))];
}

/**
 * 获取指定起点的终点列表
 */
export function getEndPointsForStart(start) {
  return ROUTE_COMBOS.filter(r => r.start === start).map(r => r.end);
}

/**
 * 估算路线距离(km)
 */
function estimateDistance(coords) {
  let dist = 0;
  for (let i = 1; i < coords.length; i++) {
    const dlat = coords[i][0] - coords[i-1][0];
    const dlng = coords[i][1] - coords[i-1][1];
    dist += Math.sqrt(dlat*dlat + dlng*dlng) * 111;
  }
  return dist;
}

/**
 * 生成时间戳
 */
function generateTimestamps(numPoints, baseTime, durationMinutes) {
  const timestamps = [];
  const intervalMs = (durationMinutes * 60 * 1000) / (numPoints - 1);
  for (let i = 0; i < numPoints; i++) {
    timestamps.push(baseTime + i * intervalMs);
  }
  return timestamps;
}

/**
 * 生成轨迹点
 */
function generateTrajectoryPoints(coords, baseTime, durationMinutes, timeFactor = 1.0) {
  const numPoints = coords.length;
  const actualDuration = durationMinutes * timeFactor;
  const timestamps = generateTimestamps(numPoints, baseTime, actualDuration);
  return coords.map((c, i) => ({
    lat: c[0],
    lng: c[1],
    timestamp: timestamps[i]
  }));
}

/**
 * 根据起终点获取轨迹数据
 */
export function getRouteByStartEnd(start, end) {
  const combo = ROUTE_COMBOS.find(r => r.start === start && r.end === end);
  if (!combo) return null;

  const key = `${start}→${end}`;
  const mainCoords = ROUTE_COORDS[key];
  if (!mainCoords) return null;

  const dist = estimateDistance(mainCoords);
  const durationMinutes = Math.max(15, dist * 3); // 约3分钟/km，最少15分钟
  const baseTime = new Date('2024-01-15T08:00:00').getTime();

  const category = combo.category;
  let userTrajectory, referenceTrajectory;
  let timeAnomaly = false;
  let anomalyDesc = null;

  if (category === 'pass') {
    // 通过：路线相同，时间正常
    referenceTrajectory = generateTrajectoryPoints(mainCoords, baseTime, durationMinutes);
    userTrajectory = generateTrajectoryPoints(mainCoords, baseTime, durationMinutes);
    timeAnomaly = false;
    anomalyDesc = null;

  } else if (category === 'spatial') {
    // 路线偏移 + 时间偏差：用户走备选路线，参考走主路线，同时时间也有偏差
    const altKey = key + '_alt';
    const altCoords = ROUTE_COORDS[altKey] || mainCoords;
    
    referenceTrajectory = generateTrajectoryPoints(mainCoords, baseTime, durationMinutes);
    const timeFactor = 1.5 + Math.random() * 0.5; // 1.5x - 2.0x 时间
    const altDuration = durationMinutes * timeFactor;
    userTrajectory = generateTrajectoryPoints(altCoords, baseTime, altDuration, 1.0);
    timeAnomaly = true;
    anomalyDesc = `用户轨迹偏移参考路线且行驶耗时约为参考的${timeFactor.toFixed(1)}倍，空间/时间偏移过大`;

  } else if (category === 'time') {
    // 时间异常：路线相同，但用户花费更多时间
    referenceTrajectory = generateTrajectoryPoints(mainCoords, baseTime, durationMinutes);
    const timeFactor = 1.8 + Math.random() * 0.7; // 1.8x - 2.5x 时间
    userTrajectory = generateTrajectoryPoints(mainCoords, baseTime, durationMinutes, timeFactor);
    timeAnomaly = true;
    anomalyDesc = `用户行驶耗时约为参考路线的${timeFactor.toFixed(1)}倍，存在显著时间偏差`;

  } else if (category === 'both') {
    // 路线偏移 + 时间异常
    const altKey = key + '_alt';
    const altCoords = ROUTE_COORDS[altKey] || mainCoords;
    
    referenceTrajectory = generateTrajectoryPoints(mainCoords, baseTime, durationMinutes);
    const timeFactor = 1.8 + Math.random() * 0.7;
    const altDuration = durationMinutes * timeFactor;
    userTrajectory = generateTrajectoryPoints(altCoords, baseTime, altDuration, 1.0);
    timeAnomaly = true;
    anomalyDesc = `用户轨迹偏移参考路线且行驶耗时约为参考的${timeFactor.toFixed(1)}倍，空间/时间偏移过大`;
  }

  return {
    start,
    end,
    category,
    label: combo.label,
    userTrajectory,
    referenceTrajectory,
    timeAnomaly,
    anomalyDesc,
    distance: dist.toFixed(1),
    duration: durationMinutes.toFixed(0)
  };
}
